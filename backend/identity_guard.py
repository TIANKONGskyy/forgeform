"""
可识别特征检测（2026-10-17）

══════════════════════════════════════════════════════════════════════
要解决的真问题
══════════════════════════════════════════════════════════════════════
宇凯要"菠萝，去掉四肢，头部简约" → 出了纯黄剪影 → 3D 重建出带碎片的板子。

不是代码 bug，是**需求把物体最可识别的特征抹掉了**：
  · 菠萝靠"菱形鳞片纹理 + 顶端叶冠"被认出来
  · 「头部简约」「去掉四肢」恰好要求抹平它们
  · 剩下的椭圆黄色块 → 模型不知道怎么画 → 给个剪影
  · 剪影做 3D → 一张薄板（长薄比 145）→ 质量闸判不合格 → 兜底重跑 → 还是薄板

光调提示词无解（我试过，越调越糟）。真正的解法是**在动 GPU 之前就问清楚**。

══════════════════════════════════════════════════════════════════════
怎么判断（不调 LLM，纯规则，毫秒级）
══════════════════════════════════════════════════════════════════════
① 找出需求里的**主体名词**（菠萝 / 拖鞋 / 熊大…）
② 查它的**识别特征清单**（靠什么被人认出来）
③ 看需求里有没有**抹除/简化**类指令（去掉 / 简约 / 不要 / 简化…）
④ 两者相交 → 该问用户

误判风险与对策：
  · 表里没有的主体 → 不拦（宁可放过，不要误拦）✓
  · 抹除词是"去掉背景/去掉文字"这类无关项 → 不拦 ✓
  · 只拦"抹掉的正好是识别特征"这一种情况
"""

from __future__ import annotations

import re

# ══════════════════════════════════════════════════════════════════════
# 物体的识别特征清单
# ══════════════════════════════════════════════════════════════════════
#
# 每条：主体关键词 → (该物体靠什么被认出来, 人类可读的特征名)
#
# ★ 只收"抹掉就认不出来"的特征，不是所有细节。
#   比如菠萝的叶冠——没有它就是个黄球，必须收。
#   而菠萝的"底部小尖"抹掉无所谓，不收。
IDENTITY_FEATURES: dict[str, tuple[tuple[str, ...], str]] = {
    "菠萝": (("叶冠", "叶子", "顶端叶", "菱形纹", "鳞片", "格子纹", "纹理", "格子"),
             "叶冠和菱形鳞片纹理"),
    "凤梨": (("叶冠", "叶子", "菱形纹", "鳞片", "纹理"),
             "叶冠和菱形鳞片纹理"),
    "草莓": (("籽", "芝麻点", "绿蒂", "叶子", "纹理"), "表面的籽点和绿蒂"),
    "西瓜": (("条纹", "绿皮", "藤蔓", "蒂"), "绿皮条纹"),
    "香蕉": (("弯", "棱", "皮", "褐色斑点"), "弯曲的棱状外形"),
    "拖鞋": (("洞", "鞋带", "鞋面", "鞋底", "包脚"), "鞋面/鞋底的拖鞋结构"),
    "鞋子": (("鞋带", "鞋面", "鞋底", "鞋跟"), "鞋面鞋底结构"),
    # ★ 杯垫/笔筒这类**基础几何体**不登记识别特征：
    #   它们靠"圆/方/筒"这种最简形状就能认出来，
    #   要求"极简"不会毁掉识别性 —— 登记了反而会误拦正常需求 ✗
    #   （实测："茶杯垫，极简" 曾因为"圆"被误判成冲突）
    "花瓶": (("瓶口", "瓶颈", "底", "腹"), "瓶口和瓶腹曲线"),
    "熊大": (("棕色", "圆脸", "红色马甲", "耳朵", "鼻"), "棕色圆脸和红色马甲"),
    "熊二": (("黄色", "圆脸", "肚子", "耳朵"), "黄色圆脸和大肚子"),
    "光头强": (("光头", "胡子", "帽子", "工装"), "光头和胡子"),
    "皮卡丘": (("黄", "尖耳", "红脸颊", "闪电尾巴"), "尖耳、红脸颊和闪电尾"),
    "哆啦A梦": (("蓝", "红鼻子", "铃铛", "口袋", "胡须"), "蓝身红鼻和铃铛"),
    "小黄人": (("黄", "护目镜", "背带裤", "胶囊"), "黄色胶囊身和护目镜"),
    "钢铁侠": (("反应堆", "红金", "面具", "头盔", "机甲"), "红金机甲和胸口反应堆"),
    "蜘蛛侠": (("蛛网", "红蓝", "面罩", "眼"), "红蓝战衣和蛛网纹"),
    "钟离": (("长发", "长袍", "岩", "金纹", "大袍"), "长发长袍"),
}

# 抹除/简化类指令（会把特征抹掉）
_ERASE_PATTERNS = re.compile(
    r"(去掉|不要|去除|删掉|简化|简约|极简|省略|无|没有|免|取消|抹掉|去掉)"
    r"[^，。,.；;]{0,8}"
)

# 这些"去掉"不涉及识别特征，属于正常要求 → 不该拦
_HARMLESS_ERASE = re.compile(
    r"(去掉|不要|去除|无|没有|免)"
    r"[^，。,.；;]{0,6}"
    r"(背景|文字|logo|标志|底座|支架|手臂|四肢|手脚|轮子|阴影|地面|水印)"
)

# 抹除/简化指令的触发词（单独出现也算）
_SIMPLIFY_WORDS = ("简约", "极简", "简化", "省略细节", "细节简化", "头部简约", "光滑")


def _find_subject(zh: str) -> tuple[str, tuple[str, ...], str] | None:
    """从需求里找出已知主体及其识别特征。"""
    for name, (feats, readable) in IDENTITY_FEATURES.items():
        if name in zh:
            return name, feats, readable
    return None


def _find_erase_span(zh: str) -> list[str]:
    """找出需求里所有"抹除/简化"片段。"""
    hits: list[str] = []
    for m in _ERASE_PATTERNS.finditer(zh):
        hits.append(m.group(0))
    for w in _SIMPLIFY_WORDS:
        if w in zh:
            hits.append(w)
    return hits


def feature_erasure_conflict(zh: str) -> dict | None:
    """检测「需求会抹掉物体识别特征」的冲突。

    返回 None（没冲突）或：
      {
        "subject": "菠萝",
        "features": "叶冠和菱形鳞片纹理",
        "erases": ["头部简约", ...],
      }

    ★ 判据分两条路（2026-10-17 实测调出来）：

      路 A｜**显式抹除特征**：句子点名要去掉某个特征
              "菠萝，去掉叶冠"        → 叶冠 是特征 → 拦 ✓
              "钢铁侠，去掉反应堆"    → 反应堆 是特征 → 拦 ✓

      路 B｜**整体简化指令**：句子要"简约/极简/简化/光滑"，而主体**本身**
              就是靠细节特征识别的（表里登记过）
              "菠萝，头部简约"        → 菠萝靠叶冠纹理识别 → 拦 ✓
              "茶杯垫，极简"          → 茶杯垫不在表里 → 放过 ✓

      ★ 为什么路 B 不需要特征词共现：
        用户不会说"菠萝去掉叶冠和纹理"，他只会说"头部简约"。
        要求"特征词必须在句子里"就永远拦不到真实场景 ✗（第一版就错在这）

      ★ 为什么"笔筒，去掉盖子"不该拦：
        "盖子"不是笔筒的识别特征；而匹配用的是"筒"字 →
        会误命中"笔筒"里的字。所以路 A 要**先剔掉主体名本身**再匹配 ✓
    """
    if not zh or not zh.strip():
        return None

    found = _find_subject(zh)
    if not found:
        return None                      # 不认识的主体 → 不拦
    subject, feats, readable = found

    # ★ 剔除主体名本身再匹配特征，否则"笔筒"里的"筒"会误命中"筒状结构"
    body = zh.replace(subject, "")

    span_text = " ".join(_find_erase_span(zh))

    # ── 路 A：显式抹除某个特征 ──
    hit_a: list[str] = []
    if span_text:
        # 无害抹除（去背景/文字/底座…）整句跳过
        only_harmless = bool(_HARMLESS_ERASE.search(span_text)) and not re.search(
            r"(去掉|不要|去除|删掉|简化|省略)[^，。,.；;]{0,8}(叶|纹|鳞|籽|耳|尾|反|马甲|护目|铃铛|胡子|头)",
            span_text)
        if not only_harmless:
            for f in feats:
                if f in body:
                    hit_a.append(f)

    # ── 路 B：整体简化指令（主体本身靠细节识别）──
    hit_b: list[str] = []
    if any(w in zh for w in ("简约", "极简", "简化", "光滑", "省略")):
        hit_b = [feats[0]] if feats else []

    hits = hit_a or hit_b
    if not hits:
        return None

    return {
        "subject": subject,
        "features": readable,
        "erases": (span_text.split()[:3] or ["简化/简约"]),
        "hit": hits[:4],
    }


def ask_user_message(conflict: dict, zh: str) -> str:
    """生成给用户的二选一提问。"""
    subject = conflict["subject"]
    feats = conflict["features"]
    return (
        f"这条要求我**做不到两全**，想先跟你确认一下：\n\n"
        f"「{subject}」是靠**{feats}**才认得出来的。"
        f"你要的「{'、'.join(conflict['erases'])}」正好会把它抹掉 —— "
        f"剩下的只是一团轮廓，我做出来的模型会是**一块板**，不是{subject}。\n\n"
        f"你选一个：\n"
        f"  **A. 保留特征**（好看、能认出来）—— 我按正常的{subject}做，你那句简化要求先不管\n"
        f"  **B. 坚持简化**（能认不出也没关系）—— 我照你说的做，但成品只会是个几何体轮廓\n\n"
        f"直接回「A」或「B」就行。"
    )
